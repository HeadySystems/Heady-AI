'use strict';
// Stub logger — wraps console
const createLogger = (name = 'app') => ({
  info: (...a) => console.log(`[${name}]`, ...a),
  warn: (...a) => console.warn(`[${name}]`, ...a),
  error: (...a) => console.error(`[${name}]`, ...a),
  debug: (...a) => console.debug(`[${name}]`, ...a),
  child: (sub) => createLogger(`${name}:${sub}`),
});
const logger = createLogger();
module.exports = logger;
module.exports.createLogger = createLogger;
module.exports.getLogger = createLogger;
module.exports.default = logger;
