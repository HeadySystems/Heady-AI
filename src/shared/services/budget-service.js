'use strict';
// Stub budget service
class BudgetService {
  constructor(opts = {}) { this._budgets = new Map(); }
  async allocate(id, amount) { this._budgets.set(id, amount); return { allocated: amount }; }
  async consume(id, amount) { const cur = this._budgets.get(id) || 0; this._budgets.set(id, cur - amount); return { remaining: cur - amount }; }
  async get(id) { return { budget: this._budgets.get(id) || 0 }; }
}
module.exports = BudgetService;
module.exports.BudgetService = BudgetService;
